# /// monty
# call-external = true
# run-async = true
# ///
# asyncio.Task and asyncio.create_task: scheduling, introspection, results and
# re-awaiting. Keep this file to CPython-compatible Task behaviour; cancellation
# and direct Task construction are documented limitations.
import asyncio
import sys

is_monty = sys.platform == 'monty'

# === create_task schedules without running the body yet ===
order = []


async def child():
    order.append('child')
    return 1


task = asyncio.create_task(child())
order.append('created')
assert order == ['created']
assert task.done() is False
assert repr(task).startswith("<Task pending name='")
assert await task == 1  # pyright: ignore
assert order == ['created', 'child']
assert task.done() is True
assert repr(task).startswith("<Task finished name='")


# === a created task runs while its creator waits on a sleep ===
background_order = []


async def background_tick():
    background_order.append('ran')


async def creator_sleeps():
    asyncio.create_task(background_tick())
    await asyncio.sleep(0.001)
    assert background_order == ['ran']


await creator_sleeps()  # pyright: ignore


# === gather accepts a Task and several coroutines may await the same Task ===
async def slow_child():
    await asyncio.sleep(0)
    return 5


shared = asyncio.create_task(slow_child())


async def first_waiter():
    return await shared


async def second_waiter():
    return await shared


gathered = await asyncio.gather(first_waiter(), second_waiter())  # pyright: ignore
assert gathered == [5, 5]
assert await shared == 5  # pyright: ignore
assert await asyncio.gather(shared) == [5]  # pyright: ignore


# === Task type and basic introspection ===
assert type(task).__name__ == 'Task'
assert isinstance(task, asyncio.Task)
assert repr(task).startswith('<Task ')
assert task.cancelled() is False
if is_monty:
    try:
        task.cancel()
        assert False, 'expected NotImplementedError'
    except NotImplementedError as exc:
        assert str(exc) == 'Task.cancel() is not implemented: Monty does not support cancelling tasks'
else:
    assert task.cancel() is False
assert task.get_name().startswith('Task-')
assert task.set_name('renamed') is None
assert task.get_name() == 'renamed'
assert repr(task).startswith("<Task finished name='renamed'")


# === get_coro returns the wrapped coroutine ===
async def simple():
    return 'value'


coro = simple()
simple_task = asyncio.create_task(coro)
assert simple_task.get_coro() is coro
assert await simple_task == 'value'  # pyright: ignore
assert simple_task.get_coro() is coro


# === autogenerated task names increase ===
auto_first = asyncio.create_task(simple())
auto_second = asyncio.create_task(simple())
auto_first_name = auto_first.get_name()
auto_second_name = auto_second.get_name()
assert auto_first_name.startswith('Task-')
assert auto_second_name.startswith('Task-')
assert int(auto_second_name[len('Task-') :]) > int(auto_first_name[len('Task-') :])
assert await auto_first == 'value'  # pyright: ignore
assert await auto_second == 'value'  # pyright: ignore


# === explicit names do not consume automatic name numbers ===
before_explicit = asyncio.create_task(simple())
before_explicit_name = before_explicit.get_name()
explicitly_named = asyncio.create_task(simple(), name='explicit')
after_explicit = asyncio.create_task(simple())
after_explicit_name = after_explicit.get_name()
assert int(after_explicit_name[len('Task-') :]) == int(before_explicit_name[len('Task-') :]) + 1
assert explicitly_named.get_name() == 'explicit'
assert await before_explicit == 'value'  # pyright: ignore
assert await explicitly_named == 'value'  # pyright: ignore
assert await after_explicit == 'value'  # pyright: ignore


# === set_name stringifies non-strings ===
named = asyncio.create_task(simple(), name='explicit')
assert named.get_name() == 'explicit'
named.set_name(123)
assert named.get_name() == '123'
named.set_name([1, 2])
assert named.get_name() == '[1, 2]'
assert await named == 'value'  # pyright: ignore


# === pending result() and exception() raise InvalidStateError ===
async def delayed():
    return await async_call('later')


pending = asyncio.create_task(delayed())
assert pending.done() is False
try:
    pending.result()
    raise AssertionError('expected InvalidStateError')
except asyncio.InvalidStateError as exc:
    assert str(exc) == 'Result is not set.'
try:
    pending.exception()
    raise AssertionError('expected InvalidStateError')
except asyncio.InvalidStateError as exc:
    assert str(exc) == 'Exception is not set.'
assert await pending == 'later'  # pyright: ignore
assert pending.result() == 'later'
assert pending.exception() is None


# === failed tasks store and re-raise their exception ===
async def boom():
    raise ValueError('bad')


failed = asyncio.create_task(boom())
try:
    await failed  # pyright: ignore
    raise AssertionError('expected ValueError')
except ValueError as exc:
    assert str(exc) == 'bad'
assert failed.done() is True
assert failed.cancelled() is False
assert repr(failed).startswith("<Task finished name='")
assert repr(failed.exception()) == "ValueError('bad')"
try:
    failed.result()
    raise AssertionError('expected ValueError')
except ValueError as exc:
    assert str(exc) == 'bad'
try:
    await failed  # pyright: ignore
    raise AssertionError('expected ValueError')
except ValueError as exc:
    assert str(exc) == 'bad'


# === awaiting a failed task chains the caller's handled exception ===
async def chained_failure():
    raise ValueError('inner')


try:
    raise KeyError('outer')
except Exception:
    chained_task = asyncio.create_task(chained_failure())
    try:
        await chained_task  # pyright: ignore
        raise AssertionError('expected ValueError')
    except ValueError as exc:
        assert repr(exc.__context__) == "KeyError('outer')"


# === re-awaiting a completed task returns the cached object ===
async def returns_list():
    await async_call('list')
    return [1, 2]


list_task = asyncio.create_task(returns_list())
first = await list_task  # pyright: ignore
second = await list_task  # pyright: ignore
third = list_task.result()
assert first == [1, 2]
assert first is second
assert first is third


# === multiple awaiters all receive the same result ===
async def await_task(value):
    return await value


async def shared_child():
    await async_call('shared')
    return [7]


shared = asyncio.create_task(shared_child())
results = await asyncio.gather(await_task(shared), await_task(shared), shared)  # pyright: ignore
assert results == [[7], [7], [7]]
assert results[0] is results[1]
assert results[1] is results[2]
assert await shared is results[0]  # pyright: ignore


# === gather accepts a Task directly ===
async def gathered_child():
    return 11


gathered = asyncio.create_task(gathered_child())
assert await asyncio.gather(gathered) == [11]  # pyright: ignore


# === a Task cannot await itself ===
holder = []


async def self_await():
    await holder[0]


self_task = asyncio.create_task(self_await())
holder.append(self_task)
try:
    await self_task  # pyright: ignore
    raise AssertionError('expected RuntimeError')
except RuntimeError as exc:
    assert str(exc).startswith('Task cannot await on itself:')


# === a coroutine can only back one task ===
async def duplicate_child():
    await async_call('duplicate')
    return 5


duplicate_coro = duplicate_child()
first_task = asyncio.create_task(duplicate_coro)
second_task = asyncio.create_task(duplicate_coro)
assert await first_task == 5  # pyright: ignore
try:
    await second_task  # pyright: ignore
    raise AssertionError('expected RuntimeError')
except RuntimeError as exc:
    assert str(exc) == 'cannot reuse already awaited coroutine'
assert second_task.done() is True


# === create_task rejects non-coroutines ===
for value in (42, None, 'x'):
    try:
        asyncio.create_task(value)
        raise AssertionError('expected TypeError')
    except TypeError as exc:
        assert str(exc) == f'a coroutine was expected, got {value!r}'


# === create_task signature errors ===
try:
    asyncio.create_task()
    raise AssertionError('expected TypeError')
except TypeError as exc:
    assert str(exc) == "create_task() missing 1 required positional argument: 'coro'"


# === create_task adopts an unresolved host future ===
# CPython's async_call() fixture returns an already-resolved asyncio.Future,
# which create_task rejects. Monty's external future is still pending, so
# create_task adopts it into a Task.
host_future = async_call('adopted')
try:
    adopted = asyncio.create_task(host_future)
except TypeError as exc:
    assert str(exc).startswith('a coroutine was expected, got ')
else:
    assert await adopted == 'adopted'  # pyright: ignore


# === create_task adopts a host future left pending by an early wait ===
early_future = async_call('early-adopted')
early_quick = asyncio.create_task(asyncio.sleep(0, 'quick'))
done, pending = await asyncio.wait([early_quick, early_future], return_when=asyncio.FIRST_COMPLETED)  # pyright: ignore
if sys.platform == 'monty':
    # The early wait must leave the host future pending; CPython's async_call()
    # fixture resolves it before the wait starts.
    assert done == {early_quick}
    assert pending == {early_future}
try:
    early_task = asyncio.create_task(early_future)
except TypeError as exc:
    assert str(exc).startswith('a coroutine was expected, got ')
else:
    assert await early_task == 'early-adopted'  # pyright: ignore


# === create_task accepts sleep's awaitable ===
sleep_task = asyncio.create_task(asyncio.sleep(0, 'slept'))
assert await sleep_task == 'slept'  # pyright: ignore


# === a pending host future can back only one task ===
busy_future = async_call('busy')
if sys.platform == 'monty':
    busy_first = asyncio.create_task(busy_future)
    busy_second = asyncio.create_task(busy_future)
    try:
        await busy_second  # pyright: ignore
        raise AssertionError('expected RuntimeError')
    except RuntimeError as exc:
        assert str(exc) == 'cannot reuse already awaited future'
    assert await busy_first == 'busy'  # pyright: ignore
else:
    # CPython sees an already-resolved Future and rejects it before adoption.
    try:
        asyncio.create_task(busy_future)
    except TypeError as exc:
        assert str(exc).startswith('a coroutine was expected, got ')
    else:
        raise AssertionError('expected TypeError')
    assert await busy_future == 'busy'  # pyright: ignore


# === repr and identity comparison ===
assert repr(asyncio.create_task).startswith('<function create_task at 0x')
cmp_task = asyncio.create_task(asyncio.sleep(0, 'cmp'))
assert cmp_task != 1
assert not (cmp_task == 1)
assert await cmp_task == 'cmp'  # pyright: ignore


