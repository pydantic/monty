// Wraps the Preview 1 Rust output as a WASI 0.2 component and transpiles its
// WIT interface into JavaScript bindings for browsers and Node worker threads.

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { componentNew, preview1AdapterReactorPath, transpile } from '@bytecodealliance/jco'
import { format, resolveConfig } from 'prettier'

const pkg = dirname(dirname(fileURLToPath(import.meta.url)))
const workspace = dirname(dirname(pkg))
const targetDir = process.env.CARGO_TARGET_DIR ?? join(workspace, 'target')
const corePath = join(targetDir, 'wasm32-wasip1', 'release', 'monty_wasm_runtime.wasm')
const outputDir = join(pkg, 'dist', 'worker', 'component')
const sourceTypesDir = join(pkg, 'ts', 'worker', 'component')

const [core, adapter] = await Promise.all([readFile(corePath), readFile(preview1AdapterReactorPath())])
const component = await componentNew(core, [['wasi_snapshot_preview1', adapter]])
const { files } = await transpile(component, {
  name: 'monty.component',
  instantiation: 'async',
})
const requiredFiles = [
  'monty.component.js',
  'monty.component.core.wasm',
  'monty.component.core2.wasm',
  'monty.component.core3.wasm',
  'monty.component.core4.wasm',
  'interfaces/pydantic-monty-worker.d.ts',
]
const missingFiles = requiredFiles.filter((name) => !(name in files))
if (missingFiles.length > 0) throw new Error(`Jco output is missing: ${missingFiles.join(', ')}`)

const generatedHeader = '// Generated by scripts/build-component.mjs from the component WIT. Do not edit.\n\n'
const workerTypesPath = 'interfaces/pydantic-monty-worker.d.ts'
const workerTypes = new TextDecoder().decode(files[workerTypesPath])
const facadeTypes = `${generatedHeader}import type * as Worker from './interfaces/pydantic-monty-worker.js'

export * from './interfaces/pydantic-monty-worker.js'

export interface ComponentExports {
  'pydantic:monty/worker': typeof Worker
  worker: typeof Worker
}

/** Instantiates the generated component wrapper and its core modules. */
export function instantiate(
  getCoreModule: (path: string) => WebAssembly.Module | Promise<WebAssembly.Module>,
  imports: Record<string, unknown>,
): ComponentExports | Promise<ComponentExports>
`
const prettierConfig = await resolveConfig(join(pkg, 'package.json'))
if (prettierConfig === null) throw new Error('unable to resolve the package Prettier configuration')
const [formattedFacadeTypes, formattedWorkerTypes] = await Promise.all([
  format(facadeTypes, { ...prettierConfig, filepath: 'monty.component.d.ts' }),
  format(`${generatedHeader}${workerTypes}`, { ...prettierConfig, filepath: workerTypesPath }),
])

await Promise.all([
  rm(outputDir, { recursive: true, force: true }),
  rm(sourceTypesDir, { recursive: true, force: true }),
])
await Promise.all([
  ...Object.entries(files).map(async ([name, contents]) => {
    const destination = join(outputDir, name)
    await mkdir(dirname(destination), { recursive: true })
    await writeFile(destination, contents)
  }),
  writeGeneratedType('monty.component.d.ts', formattedFacadeTypes),
  writeGeneratedType(workerTypesPath, formattedWorkerTypes),
])
console.log(`built WASI 0.2 component bindings -> ${outputDir}`)

/** Writes one formatted declaration into the TypeScript source tree. */
async function writeGeneratedType(path, contents) {
  const destination = join(sourceTypesDir, path)
  await mkdir(dirname(destination), { recursive: true })
  await writeFile(destination, contents)
}
