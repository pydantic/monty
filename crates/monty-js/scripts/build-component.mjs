// Wraps the Preview 1 Rust outputs as WASI 0.2 components and transpiles their
// WIT interfaces into JavaScript bindings for browsers and Node worker threads:
// the interpreter worker, and the protocol codec a remote (WebSocket) session uses.

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { componentNew, preview1AdapterReactorPath, transpile } from '@bytecodealliance/jco'
import { format, resolveConfig } from 'prettier'

const pkg = dirname(dirname(fileURLToPath(import.meta.url)))
const workspace = dirname(dirname(pkg))
const targetDir = process.env.CARGO_TARGET_DIR ?? join(workspace, 'target')
const outputDir = join(pkg, 'dist', 'worker', 'component')
const sourceTypesDir = join(pkg, 'ts', 'worker', 'component')
const generatedHeader = '// Generated by scripts/build-component.mjs from the component WIT. Do not edit.\n\n'
const typesPath = 'interfaces/pydantic-monty-types.d.ts'

/**
 * Each component: its Rust core module, Jco's output name, its exported
 * interface, and the types that interface declares beyond `types`.
 */
const components = [
  { crate: 'monty_wasm_runtime', name: 'monty.component', iface: 'worker', alias: 'Worker', ownTypes: [] },
  {
    crate: 'monty_wasm_proto',
    name: 'monty-proto.component',
    iface: 'codec',
    alias: 'Codec',
    ownTypes: ['DecodedFrame'],
  },
]

const adapter = await readFile(preview1AdapterReactorPath())
const built = await Promise.all(components.map(transpileComponent))

const prettierConfig = await resolveConfig(join(pkg, 'package.json'))
if (prettierConfig === null) throw new Error('unable to resolve the package Prettier configuration')
const formatted = (path, contents) => format(contents, { ...prettierConfig, filepath: path })

// Both components use `pydantic:monty/types`, so one copy of its declarations serves both.
const declarations = new Map([
  [typesPath, await formatted(typesPath, generatedHeader + decode(built[0].files[typesPath]))],
])
for (const { component, files } of built) {
  const ifacePath = `interfaces/pydantic-monty-${component.iface}.d.ts`
  declarations.set(ifacePath, await formatted(ifacePath, generatedHeader + decode(files[ifacePath])))
  declarations.set(`${component.name}.d.ts`, await formatted(`${component.name}.d.ts`, facade(component)))
}

await Promise.all([
  rm(outputDir, { recursive: true, force: true }),
  rm(sourceTypesDir, { recursive: true, force: true }),
])
await Promise.all([
  // The facades replace Jco's own `<name>.d.ts`: only they re-export the WIT types
  // that `host.ts`/`codec.ts`/`transport.ts`/`value.ts` import, so `dist` has to get
  // them too, or the published declarations drop those exports.
  ...built.flatMap(({ files }) =>
    Object.entries(files)
      .filter(([name]) => !declarations.has(name))
      .map(([name, contents]) => writeArtifact(join(outputDir, name), contents)),
  ),
  ...[...declarations].flatMap(([path, contents]) => [
    writeArtifact(join(outputDir, path), contents),
    writeArtifact(join(sourceTypesDir, path), contents),
  ]),
])
console.log(`built WASI 0.2 component bindings -> ${outputDir}`)

/** Wraps one core module as a component and transpiles it, checking Jco's file layout. */
async function transpileComponent(component) {
  const core = await readFile(join(targetDir, 'wasm32-wasip1', 'release', `${component.crate}.wasm`))
  const { files } = await transpile(await componentNew(core, [['wasi_snapshot_preview1', adapter]]), {
    name: component.name,
    instantiation: 'async',
  })
  const required = [
    `${component.name}.js`,
    ...['core', 'core2', 'core3', 'core4'].map((core) => `${component.name}.${core}.wasm`),
    typesPath,
    `interfaces/pydantic-monty-${component.iface}.d.ts`,
  ]
  const missing = required.filter((name) => !(name in files))
  if (missing.length > 0) throw new Error(`Jco output for ${component.name} is missing: ${missing.join(', ')}`)
  return { component, files }
}

/** The declarations of one component's instantiation wrapper and the WIT types it uses. */
function facade({ iface, alias, ownTypes }) {
  const own =
    ownTypes.length === 0
      ? ''
      : `export type { ${ownTypes.join(', ')} } from './interfaces/pydantic-monty-${iface}.js'\n`
  return `${generatedHeader}import type * as ${alias} from './interfaces/pydantic-monty-${iface}.js'

export * from './interfaces/pydantic-monty-types.js'
${own}
export interface ComponentExports {
  'pydantic:monty/${iface}': typeof ${alias}
  ${iface}: typeof ${alias}
}

/** Instantiates the generated component wrapper and its core modules. */
export function instantiate(
  getCoreModule: (path: string) => WebAssembly.Module | Promise<WebAssembly.Module>,
  imports: Record<string, unknown>,
): ComponentExports | Promise<ComponentExports>
`
}

/** Reads one Jco output file as text. */
function decode(contents) {
  return new TextDecoder().decode(contents)
}

/** Writes one build artifact, creating its parent directory. */
async function writeArtifact(destination, contents) {
  await mkdir(dirname(destination), { recursive: true })
  await writeFile(destination, contents)
}
